<span>
	I always found it frustrating to transfer files or snippets of text from some computer to another
	because I would have to login and 2FA and all that. So I made a little clipboard utility that
	deploys on Cloudflare workers that lets me copy/paste text, files, or URLs between devices through
	a simple web app and no authentication necessary when it's put in the unlock mode from my phone.

